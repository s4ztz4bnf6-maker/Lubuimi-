import test from "node:test";
import assert from "node:assert/strict";
import {createHash} from "node:crypto";
import {verifyPullRequest} from "./githubDelivery.mjs";
test("missing author fails closed",async()=>assert.equal((await verifyPullRequest({})).verified,false));
const p={base:{repo:{full_name:"a/b"},ref:"main"},user:{login:"alice"},title:"Fix #3",head:{sha:"abc",ref:"fix"},state:"open"};
const sha=createHash("sha1").update("blob 1\0x").digest("hex");
const args={owner:"a",repo:"b",number:4,expectedAuthor:"alice",expectedIssue:3,expectedHeadSha:"abc",expectedBase:"main",expectedBranch:"fix",expectedFiles:[{path:"x",content:"x"}],fetchFn:async u=>({ok:true,json:async()=>u.includes("/files?")?[{filename:"x",status:"added",sha}]:p})};
test("verified public PR",async()=>{const v=await verifyPullRequest(args);assert.equal(v.verified,true);assert.equal(v.accepted,false);});
test("changed content rejected",async()=>assert.equal((await verifyPullRequest({...args,expectedFiles:[{path:"x",content:"y"}]})).verified,false));
test("wrong base rejected",async()=>assert.equal((await verifyPullRequest({...args,expectedBase:"other"})).verified,false));
